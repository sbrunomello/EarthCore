package mello.skills;

/**
 * Represents the available skill categories for the MMO-style progression
 * system. The enum is intentionally small to keep the initial scope simple, but
 * is designed to be extensible via configuration for future types.
 */
public enum SkillType {
    MINING,
    FARMING,
    WOODCUTTING,
    HUNTER,
    FISHING,
    EXPLORATION
}
